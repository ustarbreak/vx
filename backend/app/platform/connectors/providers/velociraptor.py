"""Provider for 'endpoint-forensics' (engine: Velociraptor). Status: roadmap.

T5.1 — NOT generated by gen_providers.py. This is a hand-written, honest
scaffold: it does NOT fake data and does NOT auto-run live-response actions.
It speaks the Velociraptor REST API only when configured; otherwise every
method returns an explicit `unsupported` / empty result so the UI can show
"not deployed" truthfully (brief's no-fake-data rule).

Enable by setting env vars (see deploy/.env.connector.example):
  VELOCIRAPTOR_URL   e.g. https://velo.internal:8000
  VELOCIRAPTOR_TOKEN service user API token (read-only role recommended)

Live response (kill process, isolate host) stays gated: execute() refuses
destructive actions unless ALLOW_LIVE_RESPONSE=true AND dry_run=false AND
__confirm__=true — triple gate, mirroring soar.py SAFE_ACTIONS policy.
"""
from __future__ import annotations

import json
from typing import Any, Dict, List

import httpx

from app.core.config import settings
from app.platform.connectors.base import Manifest, register
from app.platform.connectors.models import ActionResult, Detection, JobState

DESTRUCTIVE_ACTIONS = {"host.isolate", "process.kill", "artifact.collect"}


@register
class VelociraptorProvider:
    manifest = Manifest(
        id="endpoint-forensics",
        engine="Velociraptor",
        service_id="endpoint-forensics",
        module="providers.velociraptor",
        version_pin="TODO_VERIFY",
        capabilities=["artifact.collect", "hunt.create"],
    )

    # ---- config helpers -----------------------------------------------------
    def _base(self) -> str | None:
        return getattr(settings, "VELOCIRAPTOR_URL", "") or None

    def _headers(self) -> Dict[str, str]:
        tok = getattr(settings, "VELOCIRAPTOR_TOKEN", "") or ""
        return {"Authorization": f"Bearer {tok}"} if tok else {}

    def _verify(self) -> bool:
        return bool(getattr(settings, "CONNECTOR_TLS_VERIFY", False))

    def _configured(self) -> bool:
        return bool(self._base() and self._headers())

    # ---- read path ----------------------------------------------------------
    async def probe(self) -> Dict[str, Any]:
        """Honest health check: server_info endpoint, never fabricated."""
        if not self._configured():
            return {"status": "not_configured",
                    "message": "Set VELOCIRAPTOR_URL + VELOCIRAPTOR_TOKEN to enable."}
        try:
            async with httpx.AsyncClient(verify=self._verify(), timeout=10) as c:
                r = await c.get(self._base().rstrip("/") + "/api/v1/server_info",
                                headers=self._headers())
                r.raise_for_status()
                info = r.json()
            return {"status": "online", "version": info.get("version", "unknown")}
        except Exception as exc:  # noqa: BLE001 — report honestly
            return {"status": "offline", "message": str(exc)}

    async def fetch_detections(self, org_id: int) -> List[Detection]:
        """Read-only artifact results from Velociraptor hunts (no writes)."""
        if not self._configured():
            return []
        out: List[Detection] = []
        try:
            async with httpx.AsyncClient(verify=self._verify(), timeout=20) as c:
                r = await c.get(self._base().rstrip("/") + "/api/v1/hunts/",
                                headers=self._headers())
                r.raise_for_status()
                for hunt in r.json().get("items", [])[:50]:
                    out.append(Detection(
                        id=f"velo-{hunt.get('hunt_id', '')}",
                        org_id=org_id,
                        service_id="endpoint-forensics",
                        title=hunt.get("description") or f"Velociraptor hunt {hunt.get('hunt_id')}",
                        source="velociraptor",
                    ))
        except Exception:  # noqa: BLE001 — empty, never fake
            return out
        return out

    # ---- write path (triple-gated) -----------------------------------------
    async def execute(self, action: str, params: Dict[str, Any],
                      dry_run: bool = False) -> ActionResult:
        if not self._configured():
            return ActionResult(JobState.unsupported,
                                message="Velociraptor not configured (URL/token missing)")
        if action in DESTRUCTIVE_ACTIONS:
            allowed = bool(getattr(settings, "ALLOW_LIVE_RESPONSE", False))
            confirmed = bool(params.pop("__confirm__", False))
            if not (allowed and not dry_run and confirmed):
                return ActionResult(JobState.blocked,
                                    message=f"'{action}' requires ALLOW_LIVE_RESPONSE=true, "
                                            "dry_run=false and explicit confirmation")
            return ActionResult(JobState.unsupported,
                                message="Live-response flow pending first successful Velociraptor "
                                        "deployment — see docs/guides/CONNECTOR-INSTALL.md TODO_VERIFY")
        if action == "hunt.create":
            flow = params.get("flow", "")
            if not flow or dry_run:
                return ActionResult(JobState.succeeded,
                                    message=f"dry-run: would create hunt for flow '{flow}'")
            try:
                async with httpx.AsyncClient(verify=self._verify(), timeout=20) as c:
                    r = await c.post(self._base().rstrip("/") + "/api/v1/create_hunt/",
                                     headers=self._headers(),
                                     content=json.dumps({"description": params.get("description", flow),
                                                         "hunt_flow": flow}))
                    r.raise_for_status()
                return ActionResult(JobState.succeeded, message="hunt created", data=r.json())
            except Exception as exc:  # noqa: BLE001
                return ActionResult(JobState.failed, message=str(exc))
        return ActionResult(JobState.unsupported, message=f"velociraptor: '{action}' not implemented")
