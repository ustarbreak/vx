"""Generate one pre-configured provider module per catalog service (T2.3/T2.4).

Owner requirement: every connector must already have its code; the operator
runs it manually following docs/guides — no backend rewrite needed, only this
thin adapter layer over app/services/connectors.py (decision #6).

Generated file pattern per engine:
  - probe()/fetch_detections() delegate to legacy_connector.LegacyConnectorProvider
    (i.e. the proven SERVICE_CONNECTORS pullers) with the service's own id/engine.
  - execute() delegates dangerous/write actions to native_actions.execute_native
    when PROVIDER_MODE=native (case.create / incident.create / playbook.run),
    otherwise returns honest `unsupported` (brief's no-fake-data rule).

Run from repo root:  python backend/app/platform/connectors/providers/gen_providers.py
"""
from __future__ import annotations

import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
CATALOG_DIR = HERE.parent.parent / "catalog"

TEMPLATE = '''\
"""{docstring}

GENERATED by gen_providers.py — do not hand-edit; regenerate instead.
Read path wraps the proven legacy pullers; write path delegates to native
executors behind PROVIDER_MODE=native. Nothing here invents data.
"""
from __future__ import annotations

from typing import Any, Dict, List

from app.platform.connectors.base import Manifest, register
from app.platform.connectors.models import ActionResult, Detection, JobState
from app.platform.connectors.providers.legacy_connector import LegacyConnectorProvider


@register
class {cls}(LegacyConnectorProvider):
    """Thin named provider so `/api/platform/capabilities` lists a distinct
    connector id for '{service_id}' instead of the generic 'legacy' entry."""

    manifest = Manifest(
        id="{connector_id}",
        engine={engine!r},
        service_id="{service_id}",
        module="providers.{module}",
        version_pin="{pin}",
        capabilities={caps},
    )

    async def execute(self, action: str, params: Dict[str, Any],
                      dry_run: bool = False) -> ActionResult:
        """Delegate known canonical actions to the native engines (T2.6);
        everything else stays honestly unsupported until deployed."""
        if action in ("case.create", "incident.create", "playbook.run"):
            from app.core.config import settings
            if settings.PROVIDER_MODE != "native":
                return ActionResult(JobState.unsupported,
                                    message=f"PROVIDER_MODE={{settings.PROVIDER_MODE!r}}: native delegation disabled")
            from app.platform.native_actions import execute_native
            user = params.pop("__user__", None)
            db = params.pop("__db__", None)
            if user is None or db is None:
                return ActionResult(JobState.failed,
                                    message="native delegation requires __user__/__db__ in params (router-injected)")
            confirm = bool(params.pop("__confirm__", False))
            status_code, res = await execute_native(db, user, action, params, dry_run, confirm)
            state = {{"ok": JobState.succeeded, "queued": JobState.running,
                     "requires_confirmation": JobState.blocked,
                     "unsupported": JobState.unsupported}}.get(res.get("status"), JobState.failed)
            return ActionResult(state, message=str(res.get("message") or res.get("reason") or ""), data=res)
        return ActionResult(JobState.unsupported, message=f"{module}: '{{action}}' not implemented")
'''


def _module_name(service_id: str) -> str:
    return re.sub(r"[^a-z0-9_]", "_", service_id.lower())


def main() -> int:
    try:
        import yaml
    except ImportError:  # pragma: no cover
        print("pyyaml required", file=sys.stderr)
        return 1
    services_dir = CATALOG_DIR / "services"
    src = services_dir if services_dir.is_dir() else CATALOG_DIR
    written = 0
    for ypath in sorted(src.glob("*.yaml")):
        d = yaml.safe_load(ypath.read_text())
        if not isinstance(d, dict) or "id" not in d:
            continue
        service_id = d["id"]
        module = _module_name(service_id)
        cls = "".join(p.capitalize() for p in module.split("_")) + "Provider"
        caps = []
        for a in d.get("actions") or []:
            caps.append({
                "name": a.get("name"),
                "dangerous": bool(a.get("dangerous", False)),
                "description": a.get("description", ""),
            })
        pin = d.get("version_pin", "") or "TODO_VERIFY"
        docstring = (f"Provider for '{service_id}' (engine: {d.get('engine', 'unknown')}). "
                     f"Status in catalog: {d.get('status', 'roadmap')}.")
        text = TEMPLATE.format(
            docstring=docstring, cls=cls, service_id=service_id,
            connector_id=service_id, engine=d.get("engine", "unknown"),
            module=module, pin=pin, caps=caps,
        )
        out = HERE / f"{module}.py"
        out.write_text(text)
        written += 1
    print(f"wrote {written} provider modules into {HERE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
