"""Co-branded PDF generation for the Partner Portal (Phase 4).

Server-side reportlab (approved design): deterministic layout, partner
branding from tenant_settings, and a sha256 of the rendered bytes stored on
the report record so a client can verify what was sent.

Pure function — no DB access here; the router supplies already-scoped data.
"""
from __future__ import annotations

import hashlib
import io
from typing import Any, Dict, List

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


def _hex(raw: str | None, fallback: str) -> str:
    if raw and raw.strip().startswith("#") and len(raw.strip()) >= 7:
        return raw.strip()[:7]
    return fallback


def render_report_pdf(
    *,
    title: str,
    period: str,
    partner_name: str,
    client_name: str,
    branding: Dict[str, Any],
    kpis: List[Dict[str, str]],                 # [{label, value}]
    sections: List[Dict[str, Any]],             # [{heading, columns:[..], rows:[[..]]}]
    footer: str = "",
) -> bytes:
    """Render one A4 co-branded report and return the PDF bytes."""
    accent = _hex(branding.get("primary_color"), "#0e7490")
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=18 * mm, rightMargin=18 * mm, topMargin=20 * mm, bottomMargin=16 * mm,
        title=title, author=partner_name,
    )
    ss = getSampleStyleSheet()
    h_accent = ParagraphStyle("HAccent", parent=ss["Heading1"], textColor=colors.HexColor(accent), fontSize=17, spaceAfter=2)
    sub = ParagraphStyle("Sub", parent=ss["Normal"], textColor=colors.HexColor("#475569"), fontSize=9.5)
    sec = ParagraphStyle("Sec", parent=ss["Heading2"], textColor=colors.HexColor("#0f172a"), fontSize=12, spaceBefore=10, spaceAfter=4)
    small = ParagraphStyle("Small", parent=ss["Normal"], fontSize=8.5, textColor=colors.HexColor("#64748b"))

    story: List[Any] = []
    brand = branding.get("brand_name") or partner_name
    story.append(Paragraph(f"{brand} &middot; {title}", h_accent))
    meta = f"Client: <b>{client_name}</b> &nbsp;|&nbsp; Period: {period}"
    if branding.get("support_email"):
        meta += f" &nbsp;|&nbsp; {branding['support_email']}"
    story.append(Paragraph(meta, sub))
    story.append(Spacer(1, 6 * mm))

    if kpis:
        kt = Table([[k["label"] for k in kpis], [k["value"] for k in kpis]])
        kt.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor(accent)),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, 0), 8),
            ("FONTSIZE", (0, 1), (-1, 1), 12),
            ("FONTNAME", (0, 1), (-1, 1), "Helvetica-Bold"),
            ("ALIGN", (0, 0), (-1, -1), "CENTER"),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ]))
        story.append(kt)

    for s in sections:
        story.append(Paragraph(s["heading"], sec))
        data = [s.get("columns", [])] + list(s.get("rows", []))
        if data and any(data):
            t = Table(data, repeatRows=1)
            style = [
                ("FONTSIZE", (0, 0), (-1, -1), 8.5),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#cbd5e1")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("TOPPADDING", (0, 0), (-1, -1), 3.5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3.5),
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ]
            t.setStyle(TableStyle(style))
            story.append(t)
        else:
            story.append(Paragraph("No entries for this period.", small))
        story.append(Spacer(1, 3 * mm))

    def _footer(canvas, _doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 7.5)
        canvas.setFillColor(colors.HexColor("#94a3b8"))
        canvas.drawString(18 * mm, 10 * mm, footer or f"Generated by InfraCentra SOC for {brand}")
        canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"Page {canvas.getPageNumber()}")
        canvas.restoreState()

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()


def sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()
